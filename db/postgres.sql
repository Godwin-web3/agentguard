-- AgentGuard Postgres schema (Supabase). Applied into the current search_path (schema "agentguard" in production).
-- Mirrors the SQLite schema created by the services; timestamps are ISO-8601 TEXT so both backends behave identically.
-- Every table has RLS enabled with NO policies: anon/authenticated (PostgREST) see nothing; only the server-side
-- owner role used by the app connects. Audit log and anchors are append-only via triggers.

CREATE TABLE IF NOT EXISTS mandates (
  mandate_id TEXT PRIMARY KEY, user_id TEXT NOT NULL, agent_id TEXT NOT NULL, body TEXT NOT NULL,
  mandate_hash TEXT NOT NULL, signature TEXT, status TEXT NOT NULL, created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
  user_signature TEXT, revocation_signature TEXT);
CREATE TABLE IF NOT EXISTS payments (
  payment_id TEXT PRIMARY KEY, mandate_id TEXT NOT NULL REFERENCES mandates(mandate_id), agent_id TEXT NOT NULL,
  idempotency_key TEXT NOT NULL, proposal_hash TEXT NOT NULL, amount_minor INTEGER NOT NULL, currency TEXT NOT NULL,
  status TEXT NOT NULL, evaluation TEXT NOT NULL, proposal TEXT NOT NULL,
  paypal_order_id TEXT, paypal_authorization_id TEXT, paypal_capture_id TEXT, error TEXT,
  created_at TEXT NOT NULL, updated_at TEXT NOT NULL, UNIQUE (mandate_id, agent_id, idempotency_key));
CREATE INDEX IF NOT EXISTS payments_mandate_status ON payments(mandate_id, status);
CREATE INDEX IF NOT EXISTS payments_status_updated ON payments(status, updated_at);
CREATE TABLE IF NOT EXISTS approvals (
  approval_id TEXT PRIMARY KEY, payment_id TEXT NOT NULL REFERENCES payments(payment_id), proposal_hash TEXT NOT NULL,
  expires_at TEXT NOT NULL, resolved_at TEXT, resolution TEXT, nonce TEXT, nonce_expires_at TEXT, decision_request TEXT);
CREATE INDEX IF NOT EXISTS approvals_payment ON approvals(payment_id);
CREATE TABLE IF NOT EXISTS audit (
  seq INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, ts TEXT NOT NULL, event TEXT NOT NULL, ref TEXT,
  payload TEXT NOT NULL, prev_hash TEXT NOT NULL, hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS audit_anchors (
  anchor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, size INTEGER NOT NULL, root TEXT NOT NULL,
  statement TEXT NOT NULL, statement_hash TEXT NOT NULL, timestamps TEXT NOT NULL, anchored_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS passkeys (credential_id TEXT PRIMARY KEY, user_id TEXT NOT NULL, public_key TEXT NOT NULL,
  counter INTEGER NOT NULL, transports TEXT, created_at TEXT NOT NULL, enrollment TEXT);
CREATE UNIQUE INDEX IF NOT EXISTS passkeys_one_per_user ON passkeys(user_id);
CREATE TABLE IF NOT EXISTS passkey_registrations (user_id TEXT PRIMARY KEY, challenge TEXT NOT NULL, expires_at TEXT NOT NULL, token_hash TEXT);
CREATE TABLE IF NOT EXISTS enrollment_tokens (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, via TEXT NOT NULL, issued_by TEXT NOT NULL,
  issued_at TEXT NOT NULL, expires_at TEXT NOT NULL, replaces TEXT, used_at TEXT);
CREATE TABLE IF NOT EXISTS passkey_reenroll (user_id TEXT PRIMARY KEY, nonce TEXT NOT NULL, expires_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS passkey_recoveries (recovery_id TEXT PRIMARY KEY, user_id TEXT NOT NULL, credential_id TEXT NOT NULL,
  public_key TEXT NOT NULL, counter INTEGER NOT NULL, transports TEXT, enrollment TEXT NOT NULL, replaces TEXT NOT NULL,
  started_at TEXT NOT NULL, unlock_at TEXT NOT NULL, status TEXT NOT NULL, notified INTEGER NOT NULL DEFAULT 0,
  cancel_nonce TEXT, cancel_nonce_expires_at TEXT, resolved_at TEXT);
CREATE TABLE IF NOT EXISTS receipts (receipt_id TEXT PRIMARY KEY, payment_id TEXT NOT NULL UNIQUE,
  capture_id TEXT NOT NULL, receipt_hash TEXT NOT NULL, envelope TEXT NOT NULL, issued_at TEXT NOT NULL, timestamps TEXT);
CREATE TABLE IF NOT EXISTS agents (agent_id TEXT PRIMARY KEY, user_id TEXT NOT NULL, key_hash TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS wallets (user_id TEXT PRIMARY KEY, vault_id TEXT NOT NULL, payer_email TEXT, created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS controls (key TEXT PRIMARY KEY, value TEXT NOT NULL, updated_at TEXT NOT NULL);
-- Issuer signing keys, AES-256-GCM sealed under AGENTGUARD_KEYRING_KEY (held only in the server's env, never here).
CREATE TABLE IF NOT EXISTS issuer_keys (kid TEXT PRIMARY KEY, ord INTEGER NOT NULL, created TEXT, retired TEXT, compromised_at TEXT, enc_private TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS wallet_setups (state TEXT PRIMARY KEY, user_id TEXT NOT NULL, setup_token_id TEXT NOT NULL, expires_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS agent_rate (agent_id TEXT NOT NULL, at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS agent_rate_agent_at ON agent_rate(agent_id, at);

CREATE OR REPLACE FUNCTION agentguard_append_only() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN RAISE EXCEPTION '%', TG_ARGV[0]; END $$;
DROP TRIGGER IF EXISTS audit_no_update ON audit;
DROP TRIGGER IF EXISTS audit_no_delete ON audit;
DROP TRIGGER IF EXISTS audit_no_truncate ON audit;
DROP TRIGGER IF EXISTS anchors_no_update ON audit_anchors;
DROP TRIGGER IF EXISTS anchors_no_delete ON audit_anchors;
DROP TRIGGER IF EXISTS anchors_no_truncate ON audit_anchors;
CREATE TRIGGER audit_no_update BEFORE UPDATE ON audit FOR EACH ROW EXECUTE FUNCTION agentguard_append_only('audit log is append-only');
CREATE TRIGGER audit_no_delete BEFORE DELETE ON audit FOR EACH ROW EXECUTE FUNCTION agentguard_append_only('audit log is append-only');
CREATE TRIGGER audit_no_truncate BEFORE TRUNCATE ON audit FOR EACH STATEMENT EXECUTE FUNCTION agentguard_append_only('audit log is append-only');
CREATE TRIGGER anchors_no_update BEFORE UPDATE ON audit_anchors FOR EACH ROW EXECUTE FUNCTION agentguard_append_only('anchors are append-only');
CREATE TRIGGER anchors_no_delete BEFORE DELETE ON audit_anchors FOR EACH ROW EXECUTE FUNCTION agentguard_append_only('anchors are append-only');
CREATE TRIGGER anchors_no_truncate BEFORE TRUNCATE ON audit_anchors FOR EACH STATEMENT EXECUTE FUNCTION agentguard_append_only('anchors are append-only');

DO $$ DECLARE t text; BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = current_schema() LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;
